const dicts: Record<Lang, Dict> = { ua, ru }

const Ctx = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({ lang: 'ua', t: ua, setLang: () => {} })

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      return (localStorage.getItem('am-lang') as Lang) || 'ua'
    } catch {
      return 'ua'
    }
  })
  useEffect(() => {
    document.documentElement.lang = lang === 'ua' ? 'uk' : 'ru'
    try {
      localStorage.setItem('am-lang', lang)
    } catch {
      /* storage unavailable */
    }
  }, [lang])
  return <Ctx.Provider value={{ lang, t: dicts[lang], setLang }}>{children}</Ctx.Provider>
}

export const useI18n = () => useContext(Ctx)
