// Sorting price-list lines into the catalogue tree (src/data/taxonomy.ts) by the product name.
// The price list from 1C has no categories, so the import uses these rules: the first match wins,
// so specific phrases come before general words. Names are matched lower-case (note: \\w and \\b do not work for Cyrillic in JS, hence [а-я]*), with Ukrainian
// letters folded to Russian (і→и, ї→и, є→е, ґ→г) so one pattern covers both spellings.
// `npm run catalog:import` prints every line that matched nothing; add a rule and run it again.

export const fold = (s: string) =>
  s
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[\u0456\u0457]/g, 'и')
    .replace(/є/g, 'е')
    .replace(/ґ/g, 'г')
    .replace(/'/g, '')

